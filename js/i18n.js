let currentLang = 'zh';
try {
  const saved = localStorage.getItem('parallel_lang');
  if (saved && I18N[saved]) {
    currentLang = saved;
  } else {
    const nav = (navigator.language || '').toLowerCase();
    if (nav.startsWith('ja')) currentLang = 'ja';
    else if (nav.startsWith('zh')) currentLang = 'zh';
    else currentLang = 'en';
  }
} catch (_) {}

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
}
